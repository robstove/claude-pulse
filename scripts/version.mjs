// Writes hooks/version.ts from the version in .claude-plugin/plugin.json, the one source of the version.
// The engine gives a hooks module no way to read its own manifest, and the loader imports code files only.
// Run: node scripts/version.mjs fails when the file differs from what it would write; --write writes it.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
const target = join(root, 'hooks', 'version.ts')
const { version } = JSON.parse(readFileSync(join(root, '.claude-plugin', 'plugin.json'), 'utf8'))
if (typeof version !== 'string' || version === '') {
  console.error('.claude-plugin/plugin.json states no version.')
  process.exit(1)
}

const text = [
  '// Generated by scripts/version.mjs from .claude-plugin/plugin.json. Do not edit; change the manifest and run it with --write.',
  `export const VERSION = ${JSON.stringify(version)}`,
  '',
].join('\n')

// Git can check the file out with CRLF line ends, so the comparison ignores them.
const held = existsSync(target) ? readFileSync(target, 'utf8') : ''
if (process.argv.includes('--write')) {
  writeFileSync(target, held.includes('\r\n') ? text.replace(/\n/g, '\r\n') : text)
  console.log(`hooks/version.ts written: ${version}`)
} else if (held.replace(/\r\n/g, '\n') !== text) {
  console.error(`hooks/version.ts does not match .claude-plugin/plugin.json (${version}). Run: node scripts/version.mjs --write`)
  process.exit(1)
} else console.log(`version ok: ${version}`)
